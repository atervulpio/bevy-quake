//! The letters, drawn from lines: each a few strokes on a grid four wide and six high (the base
//! line at nought), sharp at any size, for the screen's words and the signs cut into the walls
//! alike. No picture of a letter is kept anywhere. Lower case is drawn as upper case.

/// A stroke: from one point of the grid to the next, along each polyline.
type Glyph = &'static [&'static [(f32, f32)]];

const SQUARE: Glyph = &[&[(0.0, 0.0), (4.0, 0.0), (4.0, 6.0), (0.0, 6.0), (0.0, 0.0)]];

