/// Every printable letter's strokes as segments, and where each letter's segments are, for the
/// card: a segment is (x0, y0, x1, y1) on the grid; the letter `c` (32 to 126) is at `c − 32`.
pub fn table() -> (Vec<[f32; 4]>, Vec<[u32; 2]>) {
    let mut segments = Vec::new();
    let mut index = Vec::new();
    for c in 32u8..127 {
        let first = segments.len() as u32;
        for line in glyph(c as char) {
            for pair in line.windows(2) {
                segments.push([pair[0].0, pair[0].1, pair[1].0, pair[1].1]);
            }
        }
        index.push([first, segments.len() as u32 - first]);
    }
    (segments, index)
}

/// A letter's strokes as segments on its grid.
pub fn strokes(c: char) -> Vec<((f32, f32), (f32, f32))> {
    glyph(c).iter().flat_map(|line| line.windows(2).map(|p| (p[0], p[1]))).collect()
}
